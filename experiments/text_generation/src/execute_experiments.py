    def _detect_cuda_devices(self) -> int:
        """
        Detect the number of available CUDA devices.

        Returns:
            Number of available CUDA devices

        Raises:
            CudaNotFoundError: If no CUDA devices are available
        """
        if not TORCH_AVAILABLE:
            raise CudaNotFoundError(
                "PyTorch not available. Cannot detect CUDA devices."
            )

        device_count = torch.cuda.device_count()
        if device_count == 0:
            raise CudaNotFoundError(
                "No CUDA devices found. Experiments require at least one CUDA device."
            )

        logger.info(f"Detected {device_count} CUDA device(s)")
        for i in range(device_count):
            logger.info(f"  Device {i}: {torch.cuda.get_device_name(i)}")

        return device_count

