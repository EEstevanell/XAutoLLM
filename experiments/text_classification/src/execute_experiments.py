#!/usr/bin/env python3
"""
Experiment execution script for XAutoLLM framework.

This script loads experiment configurations generated by run_experiment.py
and executes them in batches based on available CUDA devices.

Usage:
    python execute_experiments.py [--experiment_type single|multi]
"""

import argparse
import logging
import os
import sys
import json
import time
from pathlib import Path
from typing import Dict, List, Optional, Any
from multiprocessing import Process, Manager, cpu_count
import psutil

# Try importing torch for CUDA device detection
try:
    import torch

    TORCH_AVAILABLE = True
except ImportError:
    TORCH_AVAILABLE = False

# Import the configuration generator
from text_classification.src.experiment_config_generator import ExperimentConfigGenerator

# Configure logging properly
logger = logging.getLogger(__name__)
logger.setLevel(logging.INFO)
handler = logging.StreamHandler(sys.stdout)
handler.setFormatter(logging.Formatter("%(asctime)s [%(levelname)s] %(message)s"))
logger.addHandler(handler)


class CudaNotFoundError(Exception):
    """Exception raised when no CUDA devices are found but are required."""

    pass


class ExperimentExecutor:
    """Handles the execution of experiments on multiple CUDA devices."""

    def __init__(self, experiment_type: str = "single"):
        """
        Initialize the experiment executor.

        Args:
            experiment_type: Type of experiment ('single' or 'multi')

        Raises:
            CudaNotFoundError: If no CUDA devices are available
        """
        self.experiment_type = experiment_type
        self.config_generator = ExperimentConfigGenerator(experiment_type)
        self.experiments = []
        self.cuda_device_count = self._detect_cuda_devices()
        self.cpu_count = cpu_count()
        self.output_dir = Path("/home/coder/autogoal/experiments/output/logs")
        self.output_dir.mkdir(parents=True, exist_ok=True)
        logger.info(f"Available CPU cores: {self.cpu_count}")
        logger.info(f"Experiment logs will be stored in: {self.output_dir}")

    def _detect_cuda_devices(self) -> int:
        """
        Detect the number of available CUDA devices.

        Returns:
            Number of available CUDA devices

        Raises:
            CudaNotFoundError: If no CUDA devices are available
        """
        if not TORCH_AVAILABLE:
            raise CudaNotFoundError(
                "PyTorch not available. Cannot detect CUDA devices."
            )

        device_count = torch.cuda.device_count()
        if device_count == 0:
            raise CudaNotFoundError(
                "No CUDA devices found. Experiments require at least one CUDA device."
            )

        logger.info(f"Detected {device_count} CUDA device(s)")
        for i in range(device_count):
            logger.info(f"  Device {i}: {torch.cuda.get_device_name(i)}")

        return device_count

    def load_single_objective_configs(self) -> List[Dict[str, Any]]:
        """
        Load configurations for single-objective experiments.

        Returns:
            List of experiment configurations
        """
        logger.info("Loading single-objective experiment configurations")
        return self.config_generator.generate_all_experiment_configs()

    def load_multi_objective_configs(self) -> List[Dict[str, Any]]:
        """
        Load configurations for multi-objective experiments.

        Returns:
            List of experiment configurations
        """
        logger.info("Loading multi-objective experiment configurations")
        return self.config_generator.generate_all_experiment_configs()

    @staticmethod
    def execute_experiment(
        experiment_data: Dict[str, Any],
        experiment_type: str,
        device_id: int,
        cpu_cores: List[int],
        log_file_path: str,
    ) -> None:
        """
        Execute a single experiment in a dedicated process.

        This method would be replaced with actual implementation in production.

        Args:
            experiment_data: Dictionary containing experiment configuration
            device_id: CUDA device ID to use
            cpu_cores: List of CPU core IDs to use
            log_file_path: Path to the log file for this experiment
        """
        # Import necessary modules inside process
        import os
        import sys
        import torch
        import numpy as np
        import random
        from autogoal.meta_learning.distance import EuclideanDistance
        from autogoal.datasets import sst2, ag_news, liar, meld
        from autogoal.meta_learning.warm_start import WarmStart
        from autogoal.meta_learning.normalization import LogNormalizer, MinMaxNormalizer
        from autogoal.ml import AutoML, evaluation_time, accuracy
        from autogoal.datasets.semeval_2023_task_8_1 import macro_f1_plain
        from autogoal.kb import Seq, Supervised, VectorDiscrete, Sentence
        from autogoal_contrib import find_classes
        from autogoal.search import JsonLogger, ConsoleLogger
        from autogoal.search import NSPESearch
        from autogoal_transformers._manual import (
            FineTuneGenLLMClassifier,
        )
        from autogoal_transformers._manual import (
            FineTuneGenLLMClassifier,
            FineTuneLLMEmbeddingClassifier,
            LoraGenLLMClassifier,
            LoraLLMEmbeddingClassifier,
            PartialFineTuneGenLLMClassifier,
            PartialFineTuneLLMEmbeddingClassifier,
        )
        from autogoal.utils import Hour, Gb
        from autogoal.search._warm_start_pge import NSPEWarmStartSearch, NSPESearch
        from autogoal.meta_learning._logging import ExperienceLogger

        dataset_dict = {
            "sst2": sst2,
            "ag_news": ag_news,
            "liar": liar,
            "meld": meld,
        }

        experiment_id = experiment_data["experiment_id"]
        dataset_name = experiment_data["dataset"]
        dataset = dataset_dict[dataset_name]
        is_baseline = experiment_data["is_baseline"]
        config = experiment_data.get("config", dict())

        # Create a safe filename-friendly version of the experiment ID
        safe_id = "".join([c if c.isalnum() else "_" for c in experiment_id])

        # Redirect stdout and stderr to the experiment's log file
        sys.stdout = open(log_file_path, "w")
        sys.stderr = sys.stdout

        # Set up a file logger that writes to the log file
        file_logger = logging.getLogger(f"experiment_{safe_id}")
        file_logger.setLevel(logging.INFO)
        file_handler = logging.FileHandler(log_file_path)
        file_handler.setFormatter(
            logging.Formatter("%(asctime)s [%(levelname)s] %(message)s")
        )
        file_logger.addHandler(file_handler)

        # Set CPU affinity for this process
        try:
            process = psutil.Process(os.getpid())
            process.cpu_affinity(cpu_cores)
            file_logger.info(
                f"Process {os.getpid()} set CPU affinity to cores {cpu_cores}"
            )
        except Exception as e:
            file_logger.error(f"Failed to set CPU affinity: {e}")

        # Set CUDA device for this process
        os.environ["CUDA_VISIBLE_DEVICES"] = str(device_id)

        # Set environment variables for threading libraries
        cpu_count = len(cpu_cores)
        os.environ["OMP_NUM_THREADS"] = str(cpu_count)
        os.environ["MKL_NUM_THREADS"] = str(cpu_count)
        os.environ["NUMEXPR_NUM_THREADS"] = str(cpu_count)
        os.environ["OPENBLAS_NUM_THREADS"] = str(cpu_count)
        os.environ["VECLIB_MAXIMUM_THREADS"] = str(cpu_count)
        os.environ["BLIS_NUM_THREADS"] = str(cpu_count)

        file_logger.info(
            f"Executing experiment: {experiment_id} for dataset {dataset_name} on CUDA device {device_id}"
        )
        file_logger.info(f"  Baseline: {is_baseline}")
        file_logger.info(f"  CPU cores: {cpu_cores}")
        file_logger.info(f"  Thread environment variables set to: {cpu_count} threads")

        from autogoal.utils._process import initialize_cuda_multiprocessing

        initialize_cuda_multiprocessing()

        try:
            # Load the dataset data
            X_train, y_train, X_test, y_test = dataset.load()

            warm_start = WarmStart(
                positive_min_threshold=config.get("positive_min_threshold", 0.2),
                adaptative_negative_alpha_limit=config.get(
                    "adaptative_negative_alpha_limit", None
                ),
                k_pos=config.get("k_pos", 10),  # Number of experiences to consider
                k_neg=config.get("k_neg", 10),  # Number of experiences to consider
                distance=config.get("distance", EuclideanDistance),
                normalizers=config.get(
                    "normalizers", [LogNormalizer(), MinMaxNormalizer()]
                ),
                exclude=f"{config.get('exclude', '')}|_warmstart|seed", # Exclude all experience with warmstart or seed in its name
                include=config.get("include", None),
                beta_scale=config.get("beta_scale", 1.0),
                beta=config.get("beta", None),
                max_alpha=config.get("max_alpha", 0.05),
                min_alpha=config.get("min_alpha", -0.02),
            )

            # initialize the WarmStart object with the current task features
            warm_start.pre_warm_up(X_train, y_train)

            objectives = (
                (macro_f1_plain, evaluation_time)
                if experiment_type == "multi"
                else (macro_f1_plain,)
            )
            maximize = (True, False) if experiment_type == "multi" else (True,)
            optimizer = NSPESearch if is_baseline else NSPEWarmStartSearch
            seed = config.get("seed", 42)

            algorithm_registry = (
                [
                    FineTuneLLMEmbeddingClassifier,
                    PartialFineTuneLLMEmbeddingClassifier,
                    LoraLLMEmbeddingClassifier,
                ]
                + find_classes(include="WORD_EMB")
                + [
                    FineTuneGenLLMClassifier,
                    PartialFineTuneGenLLMClassifier,
                    LoraGenLLMClassifier,
                ]
                + find_classes(include="TEXT_GEN")
            )

            model = AutoML(
                input=(Seq[Sentence], Supervised[VectorDiscrete]),
                output=VectorDiscrete,
                random_state=seed,
                registry=algorithm_registry,
                evaluation_timeout=1.5 * Hour,
                memory_limit=35 * Gb,
                # multi-objective baseline uses 48 hours for search timeout
                search_timeout=48 * Hour if is_baseline and experiment_type == "multi" else 24 * Hour,
                cross_validation_steps=2,
                stratified_cross_validation=True,
                # Objective functions. Multi-objective experiments use macro_f1_plain and evaluation_time
                objectives=objectives,
                # Additional observations for logging
                observations=[("Accuracy", accuracy)],
                maximize=maximize,
                # baseline uses original search algorithm
                search_algorithm=optimizer,
                # warm_start is None if baseline, otherwise it is the prepared WarmStart object
                warm_start=None if is_baseline else warm_start,
            )

            # Initialize loggers
            loggers = [
                ConsoleLogger(),
                JsonLogger(f"titan-{dataset_name}-warm-start-id:{id}.json"),
                ExperienceLogger(
                    dataset_features=warm_start.current_dataset_features,
                    system_features=warm_start.current_system_features,
                    dataset_feature_extractor_name="TextClassificationFeatureExtractor",
                    system_feature_extractor_name="SystemFeatureExtractor",
                    alias=experiment_id,
                ),
            ]
        except Exception as e:
            file_logger.error(f"Failed to initialize framework: {e}")

        try:
            # Fit the model and evaluate
            model.fit(X_train, y_train, logger=loggers)
            results = model.score(X_test, y_test)
            print(f"{dataset_name} F1: {results}")
        except Exception as e:
            file_logger.error(f"Failure during optimization: {e}")

        # Make sure to flush and close the output file
        sys.stdout.flush()
        sys.stderr.flush()

    def execute_experiments_in_batches(self) -> List[Dict[str, Any]]:
        """
        Execute all experiments in batches based on available CUDA devices.
        Ensures baseline experiments are executed first.

        Returns:
            List of experiment results
        """
        # Load configurations based on experiment type
        if self.experiment_type == "single":
            self.experiments = self.load_single_objective_configs()
        else:  # multi
            self.experiments = self.load_multi_objective_configs()

        # Sort experiments to ensure baselines run first
        self.experiments.sort(key=lambda x: (not x["is_baseline"], x["dataset"]))

        logger.info(f"Loaded {len(self.experiments)} experiment configurations")
        logger.info(f"Baseline experiments will be executed first")

        # Track results
        all_results = []

        batch_size = self.cuda_device_count
        total_batches = (len(self.experiments) + batch_size - 1) // batch_size

        logger.info(
            f"Executing experiments in {total_batches} batches with {batch_size} experiments per batch"
        )

        # Calculate cores per process based on batch size
        cores_per_process = max(1, self.cpu_count // batch_size)

        # Execute experiments in batches
        for batch_idx in range(total_batches):
            start_idx = batch_idx * batch_size
            end_idx = min(start_idx + batch_size, len(self.experiments))
            batch = self.experiments[start_idx:end_idx]

            logger.info(
                f"Executing batch {batch_idx + 1}/{total_batches} with {len(batch)} experiments"
            )

            # Create processes for this batch
            processes = []
            batch_results = []

            for i, experiment in enumerate(batch):
                device_id = i % self.cuda_device_count

                # Calculate CPU cores for this process
                start_core = i * cores_per_process
                end_core = start_core + cores_per_process
                cpu_cores = list(range(start_core, min(end_core, self.cpu_count)))

                # Create log file path using experiment ID (sanitize for filename)
                experiment_id = experiment["experiment_id"]
                safe_id = "".join([c if c.isalnum() else "_" for c in experiment_id])
                log_file_path = self.output_dir / f"{safe_id}.log"

                # Create and start the process
                p = Process(
                    target=self.execute_experiment,
                    args=(experiment, self.experiment_type, device_id, cpu_cores, str(log_file_path)),
                )
                processes.append(p)
                p.start()
                logger.info(
                    f"Started process for experiment {experiment_id} "
                    f"on device {device_id}, log: {log_file_path}"
                )

                # Add minimal result information
                batch_results.append(
                    {
                        "experiment_id": experiment_id,
                        "dataset": experiment["dataset"],
                        "is_baseline": experiment["is_baseline"],
                        "device": device_id,
                        "cpu_cores": len(cpu_cores),
                        "log_file": str(log_file_path),
                        "status": "running",
                    }
                )

            # Wait for all processes in this batch to complete
            for p in processes:
                p.join()

            # Update result status
            for result in batch_results:
                result["status"] = "completed"

            logger.info(f"Completed batch {batch_idx + 1}/{total_batches}")

            # Add this batch's results to the overall results
            all_results.extend(batch_results)

        return all_results


def parse_arguments():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description="Execute AutoGOAL experiments with specified configurations"
    )

    parser.add_argument(
        "--experiment_type",
        type=str,
        choices=["single", "multi"],
        default="single",  # Set single-objective as default
        help="Type of experiment (single-objective or multi-objective, defaults to single)",
    )

    return parser.parse_args()


def main():
    """Main entry point for the script."""
    args = parse_arguments()

    try:
        # Initialize experiment executor
        executor = ExperimentExecutor(args.experiment_type)

        # Execute all experiments
        start_time = time.time()
        results = executor.execute_experiments_in_batches()
        end_time = time.time()

        # Log execution summary
        logger.info(
            f"Executed {len(results)} experiments in {end_time - start_time:.2f} seconds"
        )

        # Group results by dataset for better readability
        datasets = set(result["dataset"] for result in results)
        for dataset in datasets:
            dataset_results = [
                result for result in results if result["dataset"] == dataset
            ]
            logger.info(f"  {dataset}: {len(dataset_results)} experiment(s) completed")

        # Save summary of results
        summary_path = Path(
            "/home/coder/autogoal/experiments/output/experiment_summary.json"
        )
        with open(summary_path, "w") as f:
            json.dump(
                {
                    "execution_time": end_time - start_time,
                    "total_experiments": len(results),
                    "experiments": results,
                },
                f,
                indent=2,
            )
        logger.info(f"Summary saved to {summary_path}")

        # Return success
        return 0

    except CudaNotFoundError as e:
        logger.error(f"Error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Error executing experiments: {e}")
        import traceback

        logger.error(traceback.format_exc())
        return 1


if __name__ == "__main__":
    sys.exit(main())
